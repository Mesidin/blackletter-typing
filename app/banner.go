// BigBanner renders an uppercase word as 6-line ANSI Shadow block letters.
func BigBanner(s string) string {
	s = strings.ToUpper(strings.TrimSpace(s))
	if s == "" {
		return ""
	}
	var lines [6]strings.Builder
	for i, r := range s {
		glyph, ok := ansiShadow[r]
		if !ok {
			glyph = ansiShadow[' ']
		}
		for row := 0; row < 6; row++ {
			if i > 0 && r != ' ' {
				lines[row].WriteString(" ")
			}
			lines[row].WriteString(glyph[row])
		}
	}
	out := make([]string, 6)
	for row := 0; row < 6; row++ {
		out[row] = lines[row].String()
	}
	return strings.Join(out, "\n")
}

func bannerFits(banner string, width int) bool {
	if banner == "" || width < 20 {
		return false
	}
	widest := 0
	for _, line := range splitLines(banner) {
		n := len([]rune(line))
		if n > widest {
			widest = n
		}
	}
	return widest <= width
}

func splitLines(s string) []string {
	var out []string
	start := 0
	for i := 0; i < len(s); i++ {
		if s[i] == '\n' {
			out = append(out, s[start:i])
			start = i + 1
		}
	}
	out = append(out, s[start:])
	return out
}
